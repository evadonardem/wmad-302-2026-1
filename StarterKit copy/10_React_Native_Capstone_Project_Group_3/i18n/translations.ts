export const translations: Record<Language, Record<TranslationKey, string>> = { en, fil };

export const LANGUAGE_NAMES: Record<Language, string> = { en: 'English', fil: 'Filipino' };

export type TranslateFn = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match
  );
}
